# Звук: динамики проверяются микрофоном (петля). Ключ/пресет/помощник — в lib-84-audioloop.ps1.
# Только с участием пользователя: подтверждение, умеренная громкость, тишина в комнате.
Step 'Звук: проверка динамиков микрофоном' {
    if ($G.Auto) { Info 'пропущено: тест требует участия пользователя (автоматический режим)'; return }
    if (-not $G.UiOk) { Warn 'модуль окон не загрузился — тест невозможен'; return }
    $sec = New-Section 'Звук: динамики, проверенные микрофоном'
    if (-not $G.HasMic) { Add-Row $sec 'Тест' 'микрофон не обнаружен — проверка невозможна' ''; return }
    $hint = if ($G.IsLaptop) { 'Микрофон ноутбука услышит динамики сам.' } else { 'Это ПК: поднесите микрофон (или гарнитуру) вплотную к колонкам. Если колонок нет (наушники) — откажитесь.' }
    $q = "Проверка динамиков микрофоном (около 40 секунд): прозвучат тестовые сигналы и свист разной высоты, микрофон их запишет.`n$hint`nСделайте громкость около 40-50 %, в комнате должно быть тихо — не говорите во время теста.`n`nНачать?"
    if (([DiagUi]::Ask($q, 'Проверка звука микрофоном', $true)) -ne 'yes') { Add-Row $sec 'Тест' 'пропущен по вашему выбору' ''; return }
    if (-not (Ensure-AudioLoop)) { Add-Row $sec 'Тест' 'модуль звука не загрузился' 'warn'; return }

    $pre = 400; $tail = 500
    $play = {
        param($stereo)
        $rec = [DiagAudioLoop]::PlayRecord($stereo, $pre, $tail)
        Start-Sleep -Milliseconds 300
        return $rec
    }
    $dbfs = { param($v) if ($v -le 1e-6) { -99 } else { [math]::Round(20 * [math]::Log10($v), 1) } }

    # --- 1. Опорный сигнал 1 кГц, оба канала: слышит ли микрофон динамики вообще
    $rec = & $play ([DiagAudioLoop]::Tone(1000, 1200, 0.25, 2))
    if (-not $rec) {
        Add-Row $sec 'Тест' ('не удалось воспроизвести/записать звук: ' + [DiagAudioLoop]::LastError) 'warn'
        Add-Issue 'warn' 'Звук' 'петля динамик-микрофон: не удалось открыть устройство записи/воспроизведения' 'Проверьте устройства по умолчанию и разрешение микрофона для классических приложений (Параметры - Конфиденциальность - Микрофон).'
        return
    }
    $a1 = [DiagAudioLoop]::AnalyzeTone($rec, 1000, $pre)
    if ($a1[2] -lt 10) {
        if (([DiagUi]::Ask("Микрофон почти не слышит динамики.`nУвеличьте громкость, проверьте что звук не выключен, и (для ПК) поднесите микрофон к колонкам.`n`nПовторить?", 'Проверка звука микрофоном', $true)) -eq 'yes') {
            $rec = & $play ([DiagAudioLoop]::Tone(1000, 1200, 0.25, 2))
            if ($rec) { $a1 = [DiagAudioLoop]::AnalyzeTone($rec, 1000, $pre) }
        }
    }
    $G.Num.audio_snr_1k = [math]::Round($a1[2], 1)
    if ($a1[2] -lt 10) {
        Add-Row $sec 'Микрофон слышит динамики' ('нет (отношение сигнал/шум {0:N0} дБ)' -f $a1[2]) 'warn'
        Add-Issue 'info' 'Звук' 'микрофон не слышит динамики — проверьте громкость и микрофон' 'Либо динамики молчат (громкость, устройство вывода по умолчанию, драйвер), либо микрофон не работает/заглушён/шумоподавление подавляет звук. Сравните с результатом проверки микрофона голосом.'
        return
    }
    Add-Row $sec 'Микрофон слышит динамики' ('да (сигнал/шум {0:N0} дБ)' -f $a1[2]) 'ok'
    if ($a1[6] -ge 0.98) { Add-Row $sec 'Перегрузка микрофона' 'запись упирается в максимум — снизьте громкость или усиление микрофона, иначе искажения измерены неверно' 'warn' }

    # --- 2. Остальные тоны
    $rows = New-Object System.Collections.Generic.List[object]
    $res = @{}
    $res[1000] = $a1
    foreach ($t in @(@(100, 0.3), @(8000, 0.15))) {
        $rec = & $play ([DiagAudioLoop]::Tone($t[0], 1200, $t[1], 2))
        if ($rec) { $res[$t[0]] = [DiagAudioLoop]::AnalyzeTone($rec, $t[0], $pre) }
    }
    foreach ($f in 100, 1000, 8000) {
        if (-not $res.ContainsKey($f)) { continue }
        $r = $res[$f]
        $rows.Add([pscustomobject]@{
            'Сигнал'        = ('{0} Гц' -f $f)
            'Уровень, дБFS' = (& $dbfs $r[0])
            'Сигнал/шум, дБ' = ('{0:N0}' -f $r[2])
            '2-я гармоника, дБ' = $(if ($r[3] -le -98) { '—' } else { '{0:N0}' -f $r[3] })
            '3-я гармоника, дБ' = $(if ($r[4] -le -98) { '—' } else { '{0:N0}' -f $r[4] })
            'Щелчки/треск' = ('{0:N0}' -f $r[5])
        })
    }

    # --- 3. Баланс каналов (1 кГц отдельно слева и справа)
    $recL = & $play ([DiagAudioLoop]::Tone(1000, 1200, 0.25, 0))
    $recR = & $play ([DiagAudioLoop]::Tone(1000, 1200, 0.25, 1))
    $aL = $null; $aR = $null
    if ($recL) { $aL = [DiagAudioLoop]::AnalyzeTone($recL, 1000, $pre) }
    if ($recR) { $aR = [DiagAudioLoop]::AnalyzeTone($recR, 1000, $pre) }
    if ($aL) { $rows.Add([pscustomobject]@{ 'Сигнал' = '1 кГц, только левый'; 'Уровень, дБFS' = (& $dbfs $aL[0]); 'Сигнал/шум, дБ' = ('{0:N0}' -f $aL[2]); '2-я гармоника, дБ' = '—'; '3-я гармоника, дБ' = '—'; 'Щелчки/треск' = ('{0:N0}' -f $aL[5]) }) }
    if ($aR) { $rows.Add([pscustomobject]@{ 'Сигнал' = '1 кГц, только правый'; 'Уровень, дБFS' = (& $dbfs $aR[0]); 'Сигнал/шум, дБ' = ('{0:N0}' -f $aR[2]); '2-я гармоника, дБ' = '—'; '3-я гармоника, дБ' = '—'; 'Щелчки/треск' = ('{0:N0}' -f $aR[5]) }) }

    # --- 4. Свип 50 Гц - 15 кГц
    $swMs = 4000; $pts = 16
    $rec = & $play ([DiagAudioLoop]::Sweep(50, 15000, $swMs, 0.2))
    $sw = $null
    if ($rec) { $sw = [DiagAudioLoop]::AnalyzeSweep($rec, 50, 15000, $swMs, $pre, $pts) }

    Add-Table $sec 'Измерения по сигналам' $rows.ToArray()

    # ----- выводы
    if ($aL -and $aR) {
        $dead = $null
        if ($aL[2] -lt 8 -and $aR[2] -ge 15) { $dead = 'левый' } elseif ($aR[2] -lt 8 -and $aL[2] -ge 15) { $dead = 'правый' }
        $diff = (& $dbfs $aL[0]) - (& $dbfs $aR[0])
        $G.Num.audio_lr_diff = [math]::Round($diff, 1)
        if ($dead) {
            Add-Row $sec 'Баланс левый/правый' ("$dead динамик не воспроизводится (разница {0:N0} дБ)" -f [math]::Abs($diff)) 'crit'
            $dn = if ($dead -eq 'левый') { 'Левый' } else { 'Правый' }
            Add-Issue 'warn' 'Звук' ("$($dn.ToLower()) динамик не работает (микрофон его не слышит)") ('Проверьте баланс в настройках звука и положение микрофона; если с другой стороны всё в порядке - неисправен динамик, шлейф или канал усилителя.')
        } elseif ([math]::Abs($diff) -gt 10) {
            $weak = if ($diff -gt 0) { 'правый' } else { 'левый' }
            Add-Row $sec 'Баланс левый/правый' ('перекос {0:N0} дБ ({1} тише)' -f [math]::Abs($diff), $weak) 'warn'
            Add-Issue 'info' 'Звук' ("$weak канал заметно тише (на {0:N0} дБ)" -f [math]::Abs($diff)) 'Может быть из-за положения микрофона (на ПК), баланса в настройках звука либо ослабшего динамика.'
        } else {
            Add-Row $sec 'Баланс левый/правый' ('в норме (разница {0:N1} дБ)' -f [math]::Abs($diff)) 'ok'
        }
    } else { Add-Row $sec 'Баланс левый/правый' 'измерить не удалось' 'warn' }

    # искажения / дребезг на 100 Гц и 1 кГц
    foreach ($f in 100, 1000) {
        if (-not $res.ContainsKey($f)) { continue }
        $r = $res[$f]
        if ($r[2] -lt 15) {
            if ($f -eq 100) { Add-Row $sec 'Низкие частоты (100 Гц)' ('динамики почти не воспроизводят (сигнал/шум {0:N0} дБ) - для малых динамиков ноутбука это нормально' -f $r[2]) '' }
            continue
        }
        $h = [math]::Max($r[3], $r[4]); $nm = if ($f -eq 100) { 'Низкие частоты (100 Гц)' } else { 'Средние частоты (1 кГц)' }
        $bad = ($h -gt -12) -or ($r[5] -ge 3) -or ($r[8] -gt 30)
        $soft = ($h -gt -20) -or ($r[5] -ge 1)
        if ($bad) {
            Add-Row $sec $nm ('искажения/дребезг: гармоники {0:N0} дБ, щелчков {1:N0}, остаток {2:N0} %' -f $h, $r[5], $r[8]) 'warn'
            $what = if ($f -eq 100) { 'хрип/дребезг на низких частотах' } else { 'хрип/искажения звука на средних частотах' }
            Add-Issue 'warn' 'Звук' "$what (динамик или корпус дребезжат)" 'Снизьте громкость и проверьте ещё раз; если дребезг остаётся - повреждён диффузор/динамик или ослаблено крепление (в ноутбуке). Проверьте также эффекты усиления басов в настройках звука.'
        } elseif ($soft) {
            Add-Row $sec $nm ('небольшие искажения (гармоники {0:N0} дБ)' -f $h) ''
        } else {
            Add-Row $sec $nm ('чисто (гармоники {0:N0} дБ)' -f $h) 'ok'
        }
    }
    if ($res.ContainsKey(8000)) {
        $r8 = $res[8000]
        if ($r8[2] -lt 10 -and $a1[2] -ge 20) { Add-Row $sec 'Высокие частоты (8 кГц)' ('почти не слышны (сигнал/шум {0:N0} дБ)' -f $r8[2]) 'warn'; Add-Issue 'info' 'Звук' 'высокие частоты (8 кГц) практически не воспроизводятся' 'Возможна неисправность твитера/динамика либо срез микрофона; сравните на другом устройстве.' }
        else { Add-Row $sec 'Высокие частоты (8 кГц)' ('слышны (сигнал/шум {0:N0} дБ)' -f $r8[2]) 'ok' }
    }

    # свип: АЧХ
    if ($sw) {
        $freq = @(); $lv = @()
        for ($i = 0; $i -lt $pts; $i++) { $freq += $sw[2 * $i]; $lv += $sw[2 * $i + 1] }
        $t = @(); for ($i = 0; $i -lt $pts; $i++) { $t += [pscustomobject]@{ 'Частота, Гц' = ('{0:N0}' -f $freq[$i]); 'Уровень, дБ (от максимума)' = ('{0:N1}' -f $lv[$i]) } }
        Add-Table $sec 'Свип 50 Гц - 15 кГц' $t -Collapsed
        $mid = @(); for ($i = 0; $i -lt $pts; $i++) { if ($freq[$i] -ge 700 -and $freq[$i] -le 4000) { $mid += $lv[$i] } }
        if ($mid.Count -ge 2 -and ($mid | Measure-Object -Maximum).Maximum -gt -90) {
            $ref = @($mid | Sort-Object)[[int][math]::Floor($mid.Count / 2)]
            $lo = $null; $hi = $null
            for ($i = 0; $i -lt $pts; $i++) { if ($lv[$i] -ge ($ref - 12)) { if ($null -eq $lo) { $lo = $freq[$i] }; $hi = $freq[$i] } }
            if ($lo) { Add-Row $sec 'Полоса воспроизведения (-12 дБ)' ('примерно {0:N0} Гц - {1:N0} Гц' -f $lo, $hi) }
            $dips = @(); for ($i = 0; $i -lt $pts; $i++) { if ($freq[$i] -ge 300 -and $freq[$i] -le 10000 -and $lv[$i] -lt ($ref - 25)) { $dips += ('{0:N0} Гц' -f $freq[$i]) } }
            if ($dips.Count) {
                Add-Row $sec 'Провалы на свипе' ('сильные провалы АЧХ на: ' + ($dips -join ', ')) 'warn'
                Add-Issue 'info' 'Звук' ('глубокие провалы звука на частотах: ' + ($dips -join ', ')) 'Возможны дребезг/резонанс корпуса, неисправный динамик или влияние помещения (повторите тест, сместив микрофон).'
            } else { Add-Row $sec 'Равномерность свипа' 'без глубоких провалов' 'ok' }
        } else { Add-Row $sec 'Свип' 'сигнал свипа не уловлен' '' }
    }
    Add-Row $sec 'Примечание' 'Измерение грубое: зависит от комнаты, громкости, положения микрофона и его шумоподавления. Использовать для выявления явных неисправностей.'
}
