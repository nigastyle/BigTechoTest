# Периферия: клавиатура (одновременные нажатия), мышь (частота опроса, двойные срабатывания, колесо), геймпад (XInput)
# Ключ periph, окно и проверки - lib-92-periph.ps1. Только при $G.Interactive.
Step 'Периферия: клавиатура, мышь, геймпад' {
    if (-not $G.Interactive) { Info 'пропущено: тест требует участия пользователя'; return }
    $s = New-Section 'Периферия: клавиатура, мышь, геймпад'
    if (-not (Initialize-PcDiagPeriph)) { Add-Row $s 'Тест' 'не удалось запустить модуль окон' 'warn'; return }
    $go = Ask-PcDiagYesNo ("Проверка периферии: клавиатура (сколько клавиш одновременно), мышь (частота опроса, двойные клики, колесо) и геймпад, если он подключён.`nКаждый шаг можно пропустить. Займёт 2-4 минуты.`n`nНачать?") 'Проверка периферии'
    if (-not $go) { Add-Row $s 'Тест' 'пропущен пользователем'; return }
    Say '  Открыто окно проверки периферии...' 'White'
    $r = [DiagPeriph]::Run()
    $vis = $r.Visited

    # --- клавиатура
    if ($r.KbDistinct -ge 1) {
        $st = ''
        if ($r.KbMax -ge 6 -and $r.ComboBest -ge 6) { $st = 'ok' }
        elseif ($r.KbDistinct -ge 8 -and $r.KbMax -le 3) { $st = 'warn' }
        Add-Row $s 'Клавиатура: клавиш одновременно' ('до {0} (нажато разных клавиш: {1})' -f $r.KbMax, $r.KbDistinct) $st
        if ($r.ComboBest -gt 0) {
            Add-Row $s 'Сочетание W+A+S+D+Shift+Пробел' $(if ($r.ComboBest -ge 6) { 'все 6 клавиш зарегистрированы' } else { '{0} из 6 (не зарегистрированы: {1})' -f $r.ComboBest, $r.ComboMissing }) $(if ($r.ComboBest -ge 6) { 'ok' } else { '' })
        }
        if ($st -eq 'warn') { Add-Issue 'info' 'Устройства' ('клавиатура регистрирует не более {0} одновременных нажатий' -f $r.KbMax) 'Для игр нужна клавиатура с N-key rollover (игровая механическая). Обычные USB-клавиатуры держат 6 клавиш + модификаторы; PS/2 и клавиатуры с NKRO ограничений не имеют. Если вы не жали много клавиш - повторите тест.' }
    } else { Add-Row $s 'Клавиатура: клавиш одновременно' 'не проверялось' }

    # --- мышь: частота опроса
    if ($r.PollHz -gt 0) {
        $hz = [math]::Round($r.PollHz)
        $st = $(if ($hz -ge 100) { 'ok' } elseif ($hz -lt 60) { 'warn' } else { '' })
        Add-Row $s 'Мышь: частота опроса' ('около {0} Гц (пик {1} Гц)' -f $hz, [math]::Round($r.PollMax)) $st
        if ($st -eq 'warn') { Add-Issue 'warn' 'Устройства' ('мышь: низкая частота опроса (около {0} Гц, норма 125-1000 Гц)' -f $hz) 'Подключите мышь напрямую в USB-порт компьютера (не в хаб), замените батарейки и отключите режим экономии у беспроводной мыши, обновите драйвер.' }
    } elseif ($r.PollTried) { Add-Row $s 'Мышь: частота опроса' 'замер не удался (мало плавных движений)' } else { Add-Row $s 'Мышь: частота опроса' 'не проверялась' }

    # --- мышь: двойные срабатывания
    $bn = @('левой', 'правой', 'средней'); $bnU = @('ЛКМ', 'ПКМ', 'СКМ')
    for ($i = 0; $i -lt 3; $i++) {
        $n = $r.Clk[$i]
        if ($n -lt 5) { if ($i -eq 0) { Add-Row $s 'Мышь: клики левой кнопкой' $(if ($n -eq 0) { 'не проверялись' } else { "мало кликов ($n) для оценки" }) }; continue }
        $chat = $r.Chat[$i]; $fast = $r.Fast[$i]
        $bad = ($fast -ge 1) -or ($chat -ge 2)
        $txt = '{0} кликов, двойных срабатываний: {1}' -f $n, $chat
        if ($r.MinInt[$i] -ge 0) { $txt += (', минимальный интервал {0:N0} мс' -f $r.MinInt[$i]) }
        Add-Row $s ('Мышь: клики ' + $bn[$i] + ' кнопкой') $txt $(if ($bad) { 'crit' } elseif ($chat -ge 1) { 'warn' } else { 'ok' })
        if ($bad) { Add-Issue 'warn' 'Устройства' ('мышь: двойные срабатывания {0} - изношен микропереключатель' -f $bnU[$i]) 'Замените мышь или микропереключатель кнопки (Omron и аналоги); у части игровых мышей есть настройка debounce в фирменной программе. Проверьте на другом USB-порту.' }
    }

    # --- мышь: колесо и кнопки
    if ($r.WheelUp -gt 0 -or $r.WheelDown -gt 0) {
        $st = 'ok'
        if ($r.WheelUp -eq 0 -or $r.WheelDown -eq 0) { $st = 'warn' } elseif ($r.WheelGlitch -ge 2) { $st = 'warn' }
        Add-Row $s 'Мышь: колесо' ('вверх {0} / вниз {1}; ложных обратных щелчков: {2}' -f $r.WheelUp, $r.WheelDown, $r.WheelGlitch) $st
        if ($r.WheelGlitch -ge 2) { Add-Issue 'warn' 'Устройства' 'мышь: колесо даёт ложные щелчки в обратную сторону (износ или грязь энкодера)' 'Продуйте и почистите колесо; если дёргается страница при прокрутке - замените мышь.' }
        elseif ($r.WheelUp -eq 0 -or $r.WheelDown -eq 0) { Add-Issue 'warn' 'Устройства' 'мышь: колесо не регистрирует прокрутку в одну из сторон' 'Продуйте колесо, проверьте на другой мыши; при подтверждении - замена мыши.' }
        $yes = { param($b) if ($b) { 'да' } else { 'нет' } }
        Add-Row $s 'Мышь: средняя и боковые кнопки' ('средняя: {0}; назад: {1}; вперёд: {2} (боковых кнопок может не быть)' -f (& $yes $r.BtnM), (& $yes $r.BtnX1), (& $yes $r.BtnX2))
    } else { Add-Row $s 'Мышь: колесо и кнопки' 'не проверялись' }

    # --- геймпад
    if ($r.PadFound) {
        Add-Row $s 'Геймпад' ('найден (XInput); кнопок нажато {0} из 14; курки LT/RT до {1}/{2} из 255' -f $r.PadBtnsSeen, $r.TrigL, $r.TrigR)
        if ($r.DriftDone) {
            $dl = [double]$r.DriftL; $dr = [double]$r.DriftR
            $stl = $(if ($dl -ge 20) { 'crit' } elseif ($dl -ge 8) { 'warn' } else { 'ok' })
            $str = $(if ($dr -ge 20) { 'crit' } elseif ($dr -ge 8) { 'warn' } else { 'ok' })
            Add-Row $s 'Геймпад: дрифт левого стика' ('{0:N1} % (X {1:N1}, Y {2:N1})' -f $dl, $r.DriftLx, $r.DriftLy) $stl
            Add-Row $s 'Геймпад: дрифт правого стика' ('{0:N1} % (X {1:N1}, Y {2:N1})' -f $dr, $r.DriftRx, $r.DriftRy) $str
            if ($stl -ne 'ok') { Add-Issue $(if ($stl -eq 'crit') { 'crit' } else { 'warn' }) 'Устройства' ('геймпад: дрифт левого стика ({0:N0} % в покое)' -f $dl) 'Протрите и продуйте стик; если дрифт остаётся - износ потенциометра, нужна замена модуля стика или геймпада. В играх помогает увеличение мёртвой зоны.' }
            if ($str -ne 'ok') { Add-Issue $(if ($str -eq 'crit') { 'crit' } else { 'warn' }) 'Устройства' ('геймпад: дрифт правого стика ({0:N0} % в покое)' -f $dr) 'Протрите и продуйте стик; если дрифт остаётся - износ потенциометра, нужна замена модуля стика или геймпада. В играх помогает увеличение мёртвой зоны.' }
        } else { Add-Row $s 'Геймпад: дрифт стиков' 'не замерялся' }
        foreach ($m in @(@('левый', $r.VibL), @('правый', $r.VibR))) {
            if ($m[1] -eq 'skip') { continue }
            Add-Row $s ('Геймпад: вибрация, ' + $m[0] + ' мотор') $(if ($m[1] -eq 'yes') { 'работает' } else { 'НЕ РАБОТАЕТ' }) $(if ($m[1] -eq 'yes') { 'ok' } else { 'warn' })
            if ($m[1] -eq 'no') { Add-Issue 'warn' 'Устройства' ('геймпад: не работает вибрация ({0} мотор)' -f $m[0]) 'Проверьте питание/батареи и драйвер; при проводном подключении - другой кабель. Возможна неисправность мотора.' }
        }
    } elseif ($vis[4]) { Add-Row $s 'Геймпад' 'не обнаружен (XInput)' }
}
